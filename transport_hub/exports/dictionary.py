def label(col):
    return COLUMNS.get(col, (col,))[0]


def fmt_of(col):
    return COLUMNS.get(col, ("", "", "", "text"))[3]


def unit_of(col):
    return COLUMNS.get(col, ("", "", "", ""))[2]


def relabel(df, with_units=False):
    """نسخة من الجدول بأسماء أعمدة عربية (الأعمدة غير المعرّفة تبقى كما هي)."""

    def name(c):
        if c not in COLUMNS:
            return c
        lab, _, u, _ = COLUMNS[c]
        return f"{lab} ({u})" if with_units and u and u not in ("عدد",) else lab

    return df.rename(columns={c: name(c) for c in df.columns})


def dictionary_frame(cols):
    """جدول قاموس لأعمدة معينة (للورقة الأخيرة في Excel)."""
    rows = [dict(العمود=lab, الوصف=d, الوحدة=u) for c in cols if c in COLUMNS for (lab, d, u, _) in [COLUMNS[c]]]
    seen, out = set(), []
    for r in rows:
        if r["العمود"] not in seen:
            seen.add(r["العمود"])
            out.append(r)
    return out
